SAFE_TEMPLATE = (
    "Не удалось сформировать безопасное текстовое пояснение. "
    "Показаны только рассчитанные показатели. По вопросам применения "
    "лекарств обратитесь к врачу или фармацевту."
)

# Запрещённые конструкции (ТЗ 15.2).
_FORBIDDEN = [
    r"принима(й|йте|ть|ем)",
    r"вам нужно",
    r"замен(ить|ите|и|ять|яйте|а на)",
    r"стоит прин",
    r"рекоменду(ю|ем|ется).{0,20}(препарат|лекарств|витамин|бад|антибиотик)",
    r"\bдоз[аеуы]\b",
    r"\bмг\b.{0,10}(раз|день|сутки|прием)",
    r"курс лечения",
    r"назнач",
]
_FORBIDDEN_RE = re.compile("|".join(_FORBIDDEN), re.IGNORECASE)


def is_safe(text: str) -> bool:
    """True, если текст не содержит запрещённых медицинских конструкций."""
    return not _FORBIDDEN_RE.search(text or "")


def post_filter(text: str) -> tuple[str, bool]:
    """Возвращает (безопасный_текст, был_ли_заменён).

    Если модель выдала запрещённую конструкцию, текст заменяется шаблоном.
    """
    if is_safe(text):
        return text, False
    return SAFE_TEMPLATE, True
