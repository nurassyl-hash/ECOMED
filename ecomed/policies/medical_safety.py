"""Медицинская безопасность и пост-фильтр LLM (ТЗ раздел 15, FR-12).

Принцип: LLM описывает только инвентарные факты. Любой вывод модели проходит
через post_filter(); при срабатывании показывается безопасный шаблон без
LLM-текста.
"""
from __future__ import annotations

import re

